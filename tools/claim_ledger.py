#!/usr/bin/env python3
"""Ledger of every page-cited claim in the paper, paired with the cited page.

The quotation ledger (tools/quote_ledger.py) checks the wording of quotations.
Nothing checked the paraphrases that cite a page ("PHP take the PP to be a
fused determiner-head (p. 589 n. 31)", "CGEL treats X as ..."), and both
source errors found on 23 Oct 2026 were of that kind. This script finds every
page reference in the section files, works out which source it cites (the
quotation ledger's attribution: a label or citation in the same parenthesis,
else the nearest source named before it whose page range fits), and writes
the citing sentences grouped by source page, with the page's text, so that
each page is read once against every claim that cites it.

It judges nothing. A reader (human or model) does that, and records the
verdicts in a pass report.

Usage (from the repository root):
    python3 tools/claim_ledger.py [--out PATH.md] [--json PATH.json]
"""

import argparse
import datetime
import json
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import quote_ledger as ql  # noqa: E402

cq = ql.cq


def raw_pages(key):
    """{printed page: raw layout text} for a source, using the configured offset
    or the quotation ledger's folio vote."""
    f = ql.FILES.get(key)
    if not f or not (ql.LIT / f).exists():
        return None
    raw = subprocess.run(["pdftotext", "-layout", str(ql.LIT / f), "-"],
                         capture_output=True, text=True, timeout=300).stdout
    pages = raw.split("\f")
    off = ql.OFFSETS.get(key)
    if off is None:
        normed = ql.source_pages(key)
        if not normed:
            return None
        # Recover the offset the folio vote chose: the smallest printed page
        # minus 1 corresponds to index 0.
        off = min(normed) - 1
    return {i + off: p for i, p in enumerate(pages, 1)}


def claims():
    out = []
    for f in ql.inputs():
        raw = f.read_text()
        text = ql.strip_comments(raw)
        quotes = [(qs, qe) for _, _, qs, qe in cq.extract_quotes(text)]
        notes = ql.footnote_spans(text)
        refs = []
        for m in ql.PAGE_RE.finditer(text):
            refs.append((m.start(), m.end(), None, m.group(2)))
        for m in ql.CITE_RE.finditer(text):
            pages = (m.group(2) or m.group(1) or "").strip()
            if re.search(r"\d", pages):
                refs.append((m.start(), m.end(), m.group(3).split(",")[0].strip(), pages))
        for s, e, key, pages in sorted(refs):
            if any(qs <= s < qe for qs, qe in quotes):
                continue  # a page number inside a quotation
            if key is None:
                paren = ql.enclosing_paren(text, s) or ""
                key = ql.label_in(paren)
                if not key:
                    before = ql.sources_before(text, s)
                    known = [k for k in before if ql.source_pages(k) and ql.plausible(k, pages)]
                    unknown = [k for k in before if not ql.source_pages(k)]
                    key = (known or unknown or before or [None])[0]
            s0, s1 = ql.sentence_bounds(text, s, e)
            sent = cq.strip_markup(text[s0:s1]).strip()
            sent = re.sub(r"\s+", " ", sent)
            has_quote = any(s0 <= qs < s1 for qs, qe in quotes)
            in_note = any(a <= s < b for a, b in notes)
            line = text.count("\n", 0, s) + 1
            out.append({"loc": f"{f.relative_to(ql.REPO)}:{line}", "source": key or "?",
                        "pages": pages, "sentence": sent, "has_quote": has_quote,
                        "footnote": in_note})
    return out


def main():
    ap = argparse.ArgumentParser()
    today = datetime.date.today()
    ap.add_argument("--out", default=f"notes/passes/{today}-claim-ledger-pairs.md")
    ap.add_argument("--json", default=None)
    args = ap.parse_args()

    cs = claims()
    for i, c in enumerate(cs, 1):
        c["id"] = f"C{i:03d}"
    groups = {}
    for c in cs:
        for p in sorted(cq.parse_pages(c["pages"]) or []) or [None]:
            groups.setdefault((c["source"], p), []).append(c)

    cache, lines = {}, []
    lines += [f"# Claim ledger pairs, {today}", "",
              f"Generated by `tools/claim_ledger.py`: {len(cs)} page references outside quotations, "
              f"grouped by source page. Each group lists the claims citing that page, then the page text "
              f"from the local PDF. Verdicts go in the pass report, not here.", ""]
    for (src, p) in sorted(groups, key=lambda k: (k[0], k[1] or 0)):
        if src not in cache:
            cache[src] = raw_pages(src) if src != "?" else None
        lines.append(f"## {src} p. {p}")
        lines.append("")
        for c in groups[(src, p)]:
            tag = (" [quote in sentence]" if c["has_quote"] else "") + (" [footnote]" if c["footnote"] else "")
            lines.append(f"- **{c['id']}** {c['loc']} (pp. {c['pages']}){tag}: {c['sentence']}")
        lines.append("")
        pg = cache[src].get(p) if cache[src] and p else None
        if pg:
            lines += ["```text", pg.strip("\n"), "```", ""]
        else:
            lines += ["*(no local page text)*", ""]
    out = Path(args.out) if Path(args.out).is_absolute() else ql.REPO / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    if args.json:
        Path(args.json).write_text(json.dumps(cs, indent=1))
    print(out, len(cs), "claims,", len(groups), "source pages")


if __name__ == "__main__":
    main()
